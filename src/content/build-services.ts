export function getBuildServiceBySlug(slug: string): BuildServicePage | undefined {
  return buildServicePages.find((page) => page.slug === slug);
}

export function getAllBuildServiceSlugs(): string[] {
  return buildServicePages.map((page) => page.slug);
}

export function homepageServiceLink(
  title: string,
): { href: string; anchor: string } | undefined {
  for (const page of buildServicePages) {
    const match = page.homepageLinks.find((link) => link.title === title);
    if (match) {
      return { href: `/services/${page.slug}`, anchor: match.anchor };
    }
  }
  return undefined;
}

export function servicePath(slug: string): string {
  return `/services/${slug}`;
}
